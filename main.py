# Student Marks Management System

students = []
marks = []


def add_student():
    name = input("Enter student name: ")
    mark = int(input("Enter student marks out of 100: "))

    if mark >= 0 and mark <= 100:
        students.append(name)
        marks.append(mark)
        print("Student added successfully!")
    else:
        print("Please enter marks between 0 and 100.")


def show_students():
    if len(students) == 0:
        print("No student records found.")
    else:
        print("\n--- Student Records ---")

        for i in range(len(students)):
            print("Name:", students[i])
            print("Marks:", marks[i])

            if marks[i] >= 90:
                print("Grade: A")
            elif marks[i] >= 75:
                print("Grade: B")
            elif marks[i] >= 60:
                print("Grade: C")
            elif marks[i] >= 40:
                print("Grade: D")
            else:
                print("Grade: Fail")

            print("-------------------")


def search_student():
    name = input("Enter student name to search: ")
    found = False

    for i in range(len(students)):
        if students[i].lower() == name.lower():
            print("Student found!")
            print("Name:", students[i])
            print("Marks:", marks[i])
            found = True

    if found == False:
        print("Student not found.")


def calculate_average():
    if len(marks) == 0:
        print("No marks available.")
    else:
        total = 0

        for mark in marks:
            total = total + mark

        average = total / len(marks)
        print("Average marks:", average)


def show_topper():
    if len(marks) == 0:
        print("No student records available.")
    else:
        highest = max(marks)
        position = marks.index(highest)

        print("Class Topper:", students[position])
        print("Highest Marks:", highest)


def main():
    while True:
        print("\n===== STUDENT MARKS MANAGEMENT =====")
        print("1. Add Student")
        print("2. Show All Students")
        print("3. Search Student")
        print("4. Calculate Average Marks")
        print("5. Show Class Topper")
        print("6. Exit")

        choice = input("Enter your choice: ")

        if choice == "1":
            add_student()

        elif choice == "2":
            show_students()

        elif choice == "3":
            search_student()

        elif choice == "4":
            calculate_average()

        elif choice == "5":
            show_topper()

        elif choice == "6":
            print("Thank you for using the program!")
            break

        else:
            print("Invalid choice. Please try again.")


main()